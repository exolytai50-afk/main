function milestoneReached($milestone, $daysSmokeFree) {
    $hours = $daysSmokeFree * 24;
    if (isset($milestone['hours'])) return $hours >= $milestone['hours'];
    if (isset($milestone['days'])) return $daysSmokeFree >= $milestone['days'];
    return false;
}

function milestoneProgress($milestone, $daysSmokeFree) {
    $targetHours = $milestone['hours'] ?? ($milestone['days'] * 24);
    $currentHours = $daysSmokeFree * 24;
    return min(100, round($currentHours / $targetHours * 100));
}

