    <h2>Использование файлов cookie</h2>

<p>
    Настоящая Политика в отношении файлов cookie (далее — «Политика») действует в отношении 
    сайта <strong>GigaChef</strong> (далее — «Сайт») и определяет порядок использования файлов cookie 
    и аналогичных технологий.
</p>

<h3>1. Что такое файлы cookie</h3>
<p>
    Файлы cookie — это небольшие текстовые файлы, которые сохраняются на вашем устройстве 
    (компьютере, планшете, смартфоне) при посещении Сайта. Они позволяют Сайту «запоминать» 
    ваши действия и предпочтения (например, язык интерфейса, авторизацию) в течение определённого времени.
</p>

<h3>2. Какие категории cookie мы используем</h3>
<ul>
    <li>
        <strong>Строго необходимые.</strong> Обеспечивают базовую работу Сайта: авторизацию, 
        безопасность, сохранение сессии. Без них Сайт не может функционировать корректно.
    </li>
    <li>
        <strong>Функциональные.</strong> Запоминают ваши предпочтения (тема оформления, 
        язык, настройки отображения).
    </li>
    <li>
        <strong>Аналитические.</strong> Помогают нам понимать, как посетители используют Сайт, 
        какие разделы наиболее популярны. Данные собираются в обезличенном виде.
    </li>
</ul>

<h3>3. Срок хранения</h3>
<p>
    Согласие на использование файлов cookie хранится в течение <strong>6 (шести) месяцев</strong> 
    с момента его предоставления. По истечении этого срока Сайт может запросить согласие повторно.
</p>

<h3>4. Управление cookie</h3>
<p>
    Вы можете в любой момент изменить настройки файлов cookie в своём браузере: 
    удалить уже сохранённые файлы или запретить их сохранение. Обратите внимание, 
    что отключение строго необходимых cookie может привести к некорректной работе Сайта.
</p>

<h3>5. Согласие</h3>
<p>
    Продолжая использовать Сайт и нажимая кнопку «Принять» в уведомлении о файлах cookie, 
